/* ---------------------------------------------------------------- per-batch dictionaries
 * Every application/language/bo_dict_*.php (sorted by file name) may define:
 *   $BO_DICT_EXTRA   = array('en' => array(key => text), 'ar' => array(key => text));
 *   $BO_FIELDS_EXTRA = array(field => array(en, ar));          // also exported as f_<field>
 *   $BO_MENU_EXTRA   = array(content_type.name => entry);      // same shape as $BO_MENU
 *   $BO_LEGACY_EXTRA = array('English literal' => 'Arabic');   // phase-1 translation of legacy views
 * Existing keys always win: a key already defined (here or by an earlier file) is NOT overwritten and is
 * recorded in $BO_DICT_COLLISIONS ("bo_dict_x.php: dict.ar.key"), listed by scratchpad dict_check.php.
 * Each file is included in its own scope (no access to the arrays above).
 * Defensive include: a file that throws while loading (a ParseError is catchable since PHP 7, as is any Error)
 * or does not define arrays is SKIPPED, logged with log_message('error') and listed in $BO_DICT_ERRORS; any
 * output it prints (BOM, stray whitespace) is discarded. Rule for batch authors: run
 *   php -d short_open_tag=1 -l application/language/bo_dict_<batch>.php   and   scratchpad dict_check.php
 * (dict_check lints every bo_dict_*.php first and exits non-zero on any problem) before handing a batch over:
 * a skipped file silently falls back to the English/raw keys in the UI.
 */
$BO_DICT_COLLISIONS = array();
$BO_DICT_ERRORS = array();
$bo_extra_files = glob(dirname(__FILE__) . '/bo_dict_*.php');
if ($bo_extra_files) {
    sort($bo_extra_files);
    $bo_load_extra = function ($file) {
        $BO_DICT_EXTRA = array(); $BO_FIELDS_EXTRA = array(); $BO_MENU_EXTRA = array(); $BO_LEGACY_EXTRA = array();
        $level = ob_get_level();
        ob_start();
        try {
            include $file;
        } catch (Throwable $e) {
            while (ob_get_level() > $level) ob_end_clean();
            return get_class($e) . ': ' . $e->getMessage() . ' (line ' . $e->getLine() . ')';
        }
        while (ob_get_level() > $level) ob_end_clean();
        foreach (array('BO_DICT_EXTRA', 'BO_FIELDS_EXTRA', 'BO_MENU_EXTRA', 'BO_LEGACY_EXTRA') as $v) {
            if (!is_array($$v)) return '$' . $v . ' is not an array';
        }
        return array('dict' => $BO_DICT_EXTRA, 'fields' => $BO_FIELDS_EXTRA, 'menu' => $BO_MENU_EXTRA, 'legacy' => $BO_LEGACY_EXTRA);
    };
    foreach ($bo_extra_files as $bo_file) {
        $bo_x = $bo_load_extra($bo_file);
        $bo_name = basename($bo_file);
        if (!is_array($bo_x)) {
            $BO_DICT_ERRORS[] = $bo_name . ': ' . $bo_x;
            if (function_exists('log_message')) log_message('error', 'bo_dictionary: skipped ' . $bo_name . ': ' . $bo_x);
            continue;
        }
        foreach ($bo_x['dict'] as $bo_lang_code => $bo_pairs) {
            if (!isset($BO_DICT[$bo_lang_code]) || !is_array($bo_pairs)) { $BO_DICT_COLLISIONS[] = $bo_name . ': unknown language ' . $bo_lang_code; continue; }
            foreach ($bo_pairs as $bo_k => $bo_v) {
                if (isset($BO_DICT[$bo_lang_code][$bo_k])) { if ($BO_DICT[$bo_lang_code][$bo_k] !== $bo_v) $BO_DICT_COLLISIONS[] = $bo_name . ': dict.' . $bo_lang_code . '.' . $bo_k; continue; }
                $BO_DICT[$bo_lang_code][$bo_k] = $bo_v;
            }
        }
        foreach ($bo_x['fields'] as $bo_f => $bo_v) {
            if (isset($BO_FIELDS[$bo_f])) { if ($BO_FIELDS[$bo_f] !== $bo_v) $BO_DICT_COLLISIONS[] = $bo_name . ': fields.' . $bo_f; continue; }
            if (!is_array($bo_v) || count($bo_v) < 2) { $BO_DICT_COLLISIONS[] = $bo_name . ': fields.' . $bo_f . ' (not array(en, ar))'; continue; }
            $BO_FIELDS[$bo_f] = $bo_v;
            if (!isset($BO_DICT['en']['f_' . $bo_f])) $BO_DICT['en']['f_' . $bo_f] = $bo_v[0];
            if (!isset($BO_DICT['ar']['f_' . $bo_f])) $BO_DICT['ar']['f_' . $bo_f] = $bo_v[1];
        }
        foreach ($bo_x['menu'] as $bo_m => $bo_v) {
            if (isset($BO_MENU[$bo_m])) { if ($BO_MENU[$bo_m] !== $bo_v) $BO_DICT_COLLISIONS[] = $bo_name . ': menu.' . $bo_m; continue; }
            $BO_MENU[$bo_m] = $bo_v;
        }
        foreach ($bo_x['legacy'] as $bo_k => $bo_v) {
            if (isset($BO_LEGACY[$bo_k])) { if ($BO_LEGACY[$bo_k] !== $bo_v) $BO_DICT_COLLISIONS[] = $bo_name . ': legacy.' . $bo_k; continue; }
            $BO_LEGACY[$bo_k] = $bo_v;
        }
    }
}
unset($bo_extra_files, $bo_load_extra, $bo_file, $bo_x, $bo_name, $bo_lang_code, $bo_pairs, $bo_k, $bo_v, $bo_f, $bo_m);
